-- =====================================================================
-- 02. Esquema "soporte" y tablas
-- Conectado a la base soporte_db. Se puede ejecutar varias veces:
-- solo crea lo que falta y no borra datos. La aplicación también lo
-- ejecuta al arrancar (spring.sql.init en application.properties).
-- =====================================================================
CREATE SCHEMA IF NOT EXISTS soporte;

-- Personas o empresas que reportan un problema
CREATE TABLE IF NOT EXISTS soporte.clientes (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(100) NOT NULL,
    email     VARCHAR(120) NOT NULL,
    telefono  VARCHAR(15)  NOT NULL,
    empresa   VARCHAR(120),
    CONSTRAINT uk_clientes_email UNIQUE (email)
);

-- Personal que atiende las solicitudes
CREATE TABLE IF NOT EXISTS soporte.tecnicos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    email         VARCHAR(120) NOT NULL,
    telefono      VARCHAR(15)  NOT NULL,
    especialidad  VARCHAR(20)  NOT NULL,
    activo        BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_tecnicos_email UNIQUE (email),
    CONSTRAINT ck_tecnicos_especialidad
        CHECK (especialidad IN ('HARDWARE', 'SOFTWARE', 'REDES', 'IMPRESORAS'))
);

-- Pedidos de atención: cada uno pertenece a un cliente y puede tener un técnico
CREATE TABLE IF NOT EXISTS soporte.solicitudes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo               VARCHAR(120)   NOT NULL,
    descripcion          VARCHAR(1000)  NOT NULL,
    prioridad            VARCHAR(20)    NOT NULL,
    estado               VARCHAR(20)    NOT NULL,
    costo                NUMERIC(14, 2),
    cliente_id           BIGINT         NOT NULL,
    tecnico_id           BIGINT,
    fecha_creacion       TIMESTAMP      NOT NULL,
    fecha_actualizacion  TIMESTAMP      NOT NULL,
    version              BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT fk_solicitudes_cliente FOREIGN KEY (cliente_id) REFERENCES soporte.clientes (id),
    CONSTRAINT fk_solicitudes_tecnico FOREIGN KEY (tecnico_id) REFERENCES soporte.tecnicos (id),
    CONSTRAINT ck_solicitudes_prioridad CHECK (prioridad IN ('BAJA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT ck_solicitudes_estado
        CHECK (estado IN ('ABIERTA', 'EN_PROCESO', 'RESUELTA', 'CERRADA', 'CANCELADA')),
    CONSTRAINT ck_solicitudes_costo CHECK (costo IS NULL OR costo >= 0)
);

-- Índices para los filtros más usados de la API
CREATE INDEX IF NOT EXISTS ix_solicitudes_cliente ON soporte.solicitudes (cliente_id);
CREATE INDEX IF NOT EXISTS ix_solicitudes_tecnico ON soporte.solicitudes (tecnico_id);
CREATE INDEX IF NOT EXISTS ix_solicitudes_estado ON soporte.solicitudes (estado);
